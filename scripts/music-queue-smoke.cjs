const assert = require("node:assert/strict");
const Queue = require("../ui/music-queue.js");
const queue = new Queue(() => 0.31);
queue.shuffled = true;
queue.start(Array.from({ length: 170 }, (_, i) => i + 1), 80);
const played = [queue.current()];
for (let i = 0; i < 169; i++) played.push(queue.next(true));
assert.equal(new Set(played).size, 170);
assert.equal(queue.next(true), null);
assert.equal(queue.previous(), played.at(-2));
queue.repeat = "one";
assert.equal(queue.next(true), played.at(-2));
queue.repeat = "all";
queue.next(); queue.next();
assert.notEqual(queue.current(), null);
queue.shuffled = false;
queue.start([1,2,3,4,5],1);
queue.move(4,1);assert.deepEqual(queue.upcoming(),[5,2,3,4]);
queue.removeAt(2);assert.deepEqual(queue.upcoming(),[5,3,4]);
queue.selectAt(1);assert.equal(queue.current(),5);
queue.prune(new Set([1,3,4]));assert.deepEqual(queue.upcoming(),[3,4]);
console.log("PASS all 170 shuffled tracks appear once; history, repeat, reorder, removal and pruning");
